import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=readFileSync(new URL('local-demo/index.html',import.meta.url),'utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for(const s of scripts)new vm.Script(s);
const full=scripts.at(-1),start=full.indexOf('const demoKey='),end=full.indexOf('async function command(');
const core=full.slice(0,full.indexOf('// All writes'));
const local=full.slice(start,end);
const memory=new Map();const sandbox={crypto:globalThis.crypto,structuredClone,TextEncoder,localStorage:{getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)}};
vm.createContext(sandbox);vm.runInContext(core+local,sandbox);
const run=s=>vm.runInContext(s,sandbox);
await run("api('/api/action',{action:'register',division:'junior',revision:0,name:'Testperson A'})");
assert.equal(run('demoState.divisions.junior.players.length'),1);
await assert.rejects(run("api('/api/login',{password:'falsch'})"));
await run("api('/api/login',{password:'TCGCOMMUNITYLAUF'})");
await run("api('/api/action',{action:'event',division:'junior',revision:demoState.revision,date:'2026-11-01',time:'17:30'})");
await run("api('/api/action',{action:'deckAdd',division:'junior',revision:demoState.revision,name:'Pikachu',quantity:2})");
await run("api('/api/action',{action:'register',division:'junior',revision:demoState.revision,name:'Testperson B'})");
await run("api('/api/action',{action:'nextRound',division:'junior',revision:demoState.revision})");
await run("api('/api/action',{action:'winner',division:'junior',revision:demoState.revision,round:0,match:0,id:demoState.divisions.junior.rounds[0].matches[0].a})");
assert.equal(run('demoState.time'),'17:30');assert.equal(run('demoState.decks.length'),2);
const saved=JSON.parse(memory.values().next().value);assert.equal(saved.divisions.junior.players.length,2);assert(saved.divisions.junior.rounds[0].matches[0].winner);
const reload={...sandbox};vm.createContext(reload);vm.runInContext(core+local,reload);assert.equal(vm.runInContext('demoState.time',reload),'17:30');
assert(!/<script[^>]+src=/.test(html));assert(!/href="theme.css"/.test(html));
console.log('PASS: Alle Inline-Skripte syntaktisch gültig; Anmeldung, falscher/richtiger PIN, Eventdaten, Leihdecks, Turnierstart, Sieger und Speicher-Wiederherstellung geprüft. Keine externen Skripte nötig.');
